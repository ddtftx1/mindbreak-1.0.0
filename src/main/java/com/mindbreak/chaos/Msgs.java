    /** 把玩家说的话"稍微"曲解一下。 */
    public static String mangle(String original) {
        Random random = ChaosManager.RANDOM;
        return switch (random.nextInt(6)) {
            case 0 -> original + "（不是）";
            case 1 -> "【未经审核】" + original;
            case 2 -> original + "，这句话被系统吃掉了后半段";
            case 3 -> new StringBuilder(original).reverse().toString();
            case 4 -> "（小声）" + original + "（大声）";
            default -> original + "！！！";
        };
    }
